/**
 * Return advanced/follow-up courses for the active app language.
 * Vietnamese users see VI courses; all other locales see English courses.
 */
export function getAdvancedCoursesForLocale(locale) {
  const target = locale === 'vi' ? 'vi' : 'en';
  return advancedCourses.filter((course) => (course.locale || 'en') === target);
}

export function getAdvancedCourseHighlights(locale) {
  return getAdvancedCoursesForLocale(locale).slice(0, 4).map((c) => c.title);
}

export const advancedCourseHighlights = getAdvancedCourseHighlights('en');
